"""Follow-up question endpoints.

A submission can be probed with follow-up questions after the student's code is in. The questions
are generated by :mod:`app.services.question_engine` (LLM when configured, deterministic bank
otherwise). Two audiences share this router:

* Students see their own submission's questions (without the grading guide) and answer them.
* Teachers/admins generate questions on demand and see the grading guide for their own challenges.
"""
from fastapi import APIRouter, Depends, HTTPException, Request
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.api.deps import audit, get_current_user, require_roles
from app.core.config import get_settings
from app.core.database import get_db
from app.core.limiter import limiter
from app.models import Challenge, FollowUpQuestion, StudentAnswer, Submission, User
from app.models.base import Role, SubmissionStatus
from app.schemas import (
    AnswerIn,
    FollowUpQuestionOut,
    GenerateQuestionsIn,
    StudentAnswerOut,
    StudentQuestionOut,
)
from app.services.question_engine import AnswerLossError, generate_questions, questions_for_submission

router = APIRouter(prefix="/submissions/{submission_id}/questions", tags=["questions"])
teacher_or_admin = require_roles(Role.TEACHER, Role.ADMIN)


def _submission(db: Session, submission_id: str) -> Submission:
    sub = db.get(Submission, submission_id)
    if sub is None:
        raise HTTPException(404, "Submission not found.")
    return sub


def _student_owns(submission: Submission, user: User) -> bool:
    return submission.user_id == user.id


def _teacher_owns_challenge(db: Session, submission: Submission, user: User) -> bool:
    """Admins see everything; a teacher only their own challenge. Students never pass this check."""
    if user.role == Role.ADMIN:
        return True
    challenge = db.get(Challenge, submission.challenge_id)
    return challenge is not None and challenge.created_by == user.id


@router.get("", response_model=list[StudentQuestionOut])
def list_questions(submission_id: str, db: Session = Depends(get_db),
                   user: User = Depends(get_current_user)):
    """List the follow-up questions for a submission the caller owns."""
    sub = _submission(db, submission_id)
    if not _student_owns(sub, user):
        raise HTTPException(404, "Submission not found.")  # same answer whether it exists or not
    rows = questions_for_submission(db, sub.id)
    if not rows and (sub.status == SubmissionStatus.COMPLETED or get_settings().demo_mode) and not sub.is_run_only:
        try:
            generate_questions(db, sub.id)
            rows = questions_for_submission(db, sub.id)
        except Exception:
            pass
    q_ids = [q.id for q in rows]
    ans_map = {
        a.question_id: a
        for a in db.scalars(
            select(StudentAnswer).where(
                StudentAnswer.question_id.in_(q_ids),
                StudentAnswer.user_id == user.id,
            )
        )
    } if q_ids else {}
    return [StudentQuestionOut(
        id=q.id,
        submission_id=q.submission_id,
        category=q.category,
        prompt=q.prompt,
        position=q.position,
        answer=StudentAnswerOut.model_validate(ans_map[q.id]) if q.id in ans_map else None,
    ) for q in rows]


@router.post("", response_model=list[FollowUpQuestionOut], status_code=201)
@limiter.limit("10/minute")
def create_questions(request: Request, submission_id: str, body: GenerateQuestionsIn | None = None,
                     db: Session = Depends(get_db), user: User = Depends(teacher_or_admin)):
    """(Re)generate follow-up questions for a submission.

    Replaces prior questions, but refuses when students have already answered unless ``force=true``
    is passed: answers cascade from questions, so regeneration would otherwise delete student work.
    """
    sub = _submission(db, submission_id)
    if not _teacher_owns_challenge(db, sub, user):
        raise HTTPException(403, "You can only generate questions for your own challenges.")
    count = body.count if body else 4
    force = bool(body.force) if body else False
    try:
        created = generate_questions(db, sub.id, count=count, user=user, force=force)
    except AnswerLossError as exc:
        raise HTTPException(409, str(exc)) from exc
    audit(db, request, user, "questions.generate", "submission", sub.id,
          {"count": len(created), "source": created[0].source.value if created else None})
    db.commit()
    return [FollowUpQuestionOut(
        id=q.id, submission_id=q.submission_id, category=q.category, prompt=q.prompt,
        expected_points=q.expected_points, source=q.source, position=q.position,
    ) for q in created]


@router.get("/review", response_model=list[FollowUpQuestionOut])
def review_questions(request: Request, submission_id: str, db: Session = Depends(get_db),
                     user: User = Depends(teacher_or_admin)):
    """Teacher view: questions plus the grading guide, for the teacher's own challenges."""
    sub = _submission(db, submission_id)
    if not _teacher_owns_challenge(db, sub, user):
        raise HTTPException(403, "You can only review questions for your own challenges.")
    rows = questions_for_submission(db, sub.id)
    q_ids = [q.id for q in rows]
    ans_map = {}
    if q_ids:
        answers = db.scalars(select(StudentAnswer).where(StudentAnswer.question_id.in_(q_ids))).all()
        for a in answers:
            ans_map[a.question_id] = a
    audit(db, request, user, "questions.review", "submission", sub.id)
    db.commit()
    return [FollowUpQuestionOut(
        id=q.id, submission_id=q.submission_id, category=q.category, prompt=q.prompt,
        expected_points=q.expected_points, source=q.source, position=q.position,
        answer=StudentAnswerOut.model_validate(ans_map[q.id]) if q.id in ans_map else None,
    ) for q in rows]


@router.post("/{question_id}/answers", response_model=StudentAnswerOut, status_code=201)
@limiter.limit("20/minute")
def answer_question(request: Request, submission_id: str, question_id: str, body: AnswerIn,
                    db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    """Submit (or replace) the student's answer to one of their own submission's questions."""
    sub = _submission(db, submission_id)
    if not _student_owns(sub, user):
        raise HTTPException(404, "Submission not found.")
    question = db.get(FollowUpQuestion, question_id)
    if question is None or question.submission_id != sub.id:
        raise HTTPException(404, "Question not found.")
    answer = db.scalar(select(StudentAnswer).where(
        StudentAnswer.question_id == question.id, StudentAnswer.user_id == user.id))
    if answer is None:
        answer = StudentAnswer(question_id=question.id, user_id=user.id, answer_text=body.answer_text)
        db.add(answer)
    else:
        answer.answer_text = body.answer_text
        answer.score = None       # an edited answer needs re-grading
        answer.feedback = None
    if get_settings().demo_mode:
        answer.score = 0.90
        answer.feedback = "[DEMO SIMULATION] Clear reasoning demonstrated. Key algorithmic concepts accurately addressed."
    audit(db, request, user, "questions.answer", "question", question.id)
    db.commit()
    db.refresh(answer)
    return answer
